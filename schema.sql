DROP TABLE IF EXISTS registration, workshop, customer, instructor CASCADE;
CREATE TABLE instructor (
 instructor_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name VARCHAR(100) NOT NULL,
 email VARCHAR(150) NOT NULL UNIQUE
);
CREATE TABLE customer (
 customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name VARCHAR(100) NOT NULL,
 email VARCHAR(150) NOT NULL UNIQUE
);
CREATE TABLE workshop (
 workshop_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 instructor_id INTEGER NOT NULL REFERENCES instructor(instructor_id),
 title VARCHAR(150) NOT NULL,
 capacity INTEGER NOT NULL,
 start_date DATE NOT NULL,
 end_date DATE NOT NULL
);
CREATE TABLE registration (
 customer_id INTEGER NOT NULL REFERENCES customer(customer_id),
 workshop_id INTEGER NOT NULL REFERENCES workshop(workshop_id),
 registered_on DATE NOT NULL DEFAULT CURRENT_DATE,
 PRIMARY KEY (customer_id, workshop_id)
);
